  defp label_css do
    """
    .cal-multiday-bar.text-white span { text-shadow: 0 0 2px rgba(0,0,0,0.9), 0 0 3px rgba(0,0,0,0.7); }
    .cal-multiday-bar.text-neutral-900 span { text-shadow: 0 0 2px rgba(255,255,255,0.95), 0 0 3px rgba(255,255,255,0.8); }\
