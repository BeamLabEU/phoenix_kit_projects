defmodule PhoenixKitProjects.CalendarDisplay do
  @moduledoc """
  Maps projects — and, for the default Tasks mode, their scheduled tasks — to
  `PhoenixLiveCalendar.Event` structs for the Overview dashboard calendar.

  Two mapping modes back the Overview calendar's mode toggle:

    * `task_events/3` (the **Tasks** default) — every leaf task across every
      given project, placed on the days its `ScheduleLayout` span covers,
      colored by the OWNING project's identity color so a day reads as "what
      happens today, across projects". Same-day tasks stack as chips,
      multi-day tasks as bars; the LiveView caps the per-day count and the
      grid shows a Google-style "+N more" for the rest.
    * `events/6` (the **Projects** mode — the original view) — each project
      as one all-day "ongoing line": running projects span start →
      planned-end (reaching at least today, so they read as ongoing),
      completed projects span start → completion, and scheduled projects get
      a one-day marker on their planned start.

  Bars are colored by **project identity** — a stable color per project, picked
  by hashing the project id over a fixed palette of hues spread around the color
  wheel — so adjacent and stacked bars stay tellable apart. Lifecycle status is
  conveyed by the dashboard's project cards, with one exception: for a running
  summary the caller tags `late: true`, only the stretch of the bar PAST its
  planned end (planned_end+1 .. today) is highlighted — via `extra.highlight`
  with the `pk-overdue` class (it marks that stretch in the INVERSE of the bar's
  own colour — diagonal stripes over the identity colour, or a solid fill —
  animated per `animation_style/0`, all configured on `/admin/settings/projects`)
  — so the length of the marked tail shows how late the project is. The rest
  keeps its identity color.

  `end` is exclusive in PhoenixLiveCalendar (`[start, end)`), so the inclusive
  last day gets `+1`. Projects without a placeable start date are dropped.
  """

  use Gettext, backend: PhoenixKitProjects.Gettext

  alias PhoenixKitProjects.{L10n, ScheduleLayout}
  alias PhoenixKitProjects.Schemas.{Assignment, Project}
  alias PhoenixLiveCalendar.Event

  # Distinct {bg, text} pairs — fixed Tailwind hues spread around the color wheel
  # (≥28° apart), NOT daisyUI semantic colors (those clustered into several
  # near-identical pinks/reds + two blues in this theme). Each project is pinned
  # to one by hashing its id. Listed as literals so the host's Tailwind (scanning
  # this module via `css_sources/0`) emits them. (The overdue stretch shows the
  # INVERSE of each color via CSS `filter: invert`, so no color table is needed.)
  @palette [
    {"bg-blue-600", "text-white"},
    {"bg-cyan-500", "text-neutral-900"},
    {"bg-emerald-600", "text-white"},
    {"bg-lime-500", "text-neutral-900"},
    {"bg-amber-400", "text-neutral-900"},
    {"bg-orange-600", "text-white"},
    {"bg-fuchsia-600", "text-white"},
    {"bg-violet-600", "text-white"}
  ]

  # Class applied (via `extra.highlight`) to the OVERDUE day-segments of a late
  # project's bar — the stretch from its planned end to today. Its look (inverse-
  # colour stripes or solid fill) + animation is generated by `animation_style/0`
  # from the settings below.
  @overdue_class "pk-overdue"

  # Tasks-mode late marker: a red inset ring on the chip/bar (Tailwind
  # utilities as literals so the host's scan emits them; the identity color
  # stays readable underneath).
  @late_class "ring-2 ring-error ring-inset"

  # ── Overdue animation (configured on /admin/settings/projects) ──────────────
  # The overdue stretch is marked in the INVERSE of the bar's own color — either
  # as diagonal stripes (default) or a solid fill (`pattern`). These settings
  # pick the pattern + HOW it animates and generate the `<style>` the Overview
  # injects. Validated on read/write (enums against the allowed set, numbers
  # clamped) so a malformed install resolves to safe defaults.
  @module "projects"

  @anim_pattern_key "projects_cal_overdue_pattern"
  @anim_mode_key "projects_cal_overdue_mode"
  @anim_speed_key "projects_cal_overdue_speed"
  @anim_bright_min_key "projects_cal_overdue_bright_min"
  @anim_bright_max_key "projects_cal_overdue_bright_max"
  @anim_wave_step_key "projects_cal_overdue_wave_step"
  @anim_opacity_key "projects_cal_overdue_opacity"
  @late_marker_key "projects_cal_late_marker"

  # ── Grid appearance (the calendar customizer's non-overdue half) ──
  @show_weekends_key "projects_cal_show_weekends"
  @show_week_numbers_key "projects_cal_show_week_numbers"
  @fixed_weeks_key "projects_cal_fixed_weeks"
  @max_events_key "projects_cal_max_events"
  @max_multiday_key "projects_cal_max_multiday"

  # stripes = diagonal inverse-colour hazard stripes over the identity colour
  # (keeps the project's colour readable); solid = the whole overdue stretch
  # flips to the inverse colour.
  @anim_patterns ~w(stripes solid)

  # wave = motion travels (stripes slide horizontally across the bar / a band
  # sweeps); flash = pulses in place; off = static, no motion.
  @anim_modes ~w(wave flash off)

  # How anything LATE (task chips/bars + late project bars) is marked:
  # pattern (default) = the configured overdue pattern, so every calendar
  # shows lateness the same way out of the box; ring = the red inset ring
  # alternative; none = no visual marking at all (the late DATA stays — the
  # Overdue-only lens, popup badges and card tiers keep working).
  @late_markers ~w(ring pattern none)

  @default_pattern "stripes"
  # Static by default — the stripes already read as "overdue" without motion;
  # wave/flash are opt-in.
  @default_mode "off"
  @default_speed 7.0
  @default_bright_min 0.78
  @default_bright_max 1.18
  @default_wave_step 0.16
  @default_opacity 1.0
  @default_late_marker "pattern"
  @default_show_weekends true
  @default_show_week_numbers false
  @default_fixed_weeks false

  # {lo, hi} clamp ranges for each numeric setting (also bound the form inputs).
  @speed_range {1.0, 20.0}
  @bright_min_range {0.2, 1.0}
  @bright_max_range {1.0, 2.5}
  @wave_step_range {0.02, 1.0}
  @opacity_range {0.05, 1.0}
  @max_events_range {1, 6}
  @max_multiday_range {1, 8}

  @doc """
  Builds the calendar event list from the dashboard's already-loaded data.

    * `active_summaries` — `Projects.project_tree_summary/1` maps for running
      projects (carry `:project` and `:planned_end`), each tagged by the
      caller with `:late` (boolean) to drive the blink
    * `completed` / `upcoming` — `[Project.t()]` (recently completed / scheduled)
    * `lang` — content language for project titles
    * `today` — anchor so a running project's bar always reaches at least today
    * `offset` — viewer timezone offset (e.g. "+3"); UTC datetimes are converted
      to local calendar dates with it, so bars land on the same day the viewer sees

  Options:

    * `:late_marker` — how a LATE running project is marked (`"pattern"`
      default): `"pattern"` highlights the overdue stretch
      (planned_end+1 .. today) with the configured overdue pattern, so the
      marked length shows HOW late; `"ring"` rings the whole bar instead —
      the same marker late task chips wear, so one setting dresses
      everything late the same way.
  """
  @spec events(
          [map()],
          [Project.t()],
          [Project.t()],
          String.t() | nil,
          Date.t(),
          String.t(),
          keyword()
        ) ::
          [Event.t()]
  def events(
        active_summaries,
        completed,
        upcoming,
        lang,
        today \\ Date.utc_today(),
        offset \\ "0",
        opts \\ []
      ) do
    marker = Keyword.get(opts, :late_marker, "pattern")
    running = Enum.map(active_summaries, &running_event(&1, lang, today, offset, marker))
    done = Enum.map(completed, &completed_event(&1, lang, offset))
    scheduled = Enum.map(upcoming, &scheduled_event(&1, lang, offset))

    Enum.reject(running ++ done ++ scheduled, &is_nil/1)
  end

  @doc """
  Builds the Tasks-mode event list (+ a per-task metadata map) from prepared
  `{item, span}` pairs — each a `PhoenixKitProjects.ScheduleLayout` item with
  its computed `%{start: NaiveDateTime, end: NaiveDateTime}` span. Pure: the
  caller runs the schedule walk (`ScheduleLayout.tree/1` per project) and
  passes only the LEAF items (sub-project container assignments excluded —
  their child tasks stand for themselves here).

  Each task becomes an all-day event spanning its scheduled days in the
  viewer's timezone (`offset`, e.g. `"+3"` — same local basis as the rest of
  the Overview), colored by the OWNING project's identity color
  (`color_for/1`), so tasks group visually by project across the month.
  Exclusive ends (`[start, end)`): a span ending exactly at local midnight
  doesn't occupy that day, and a zero-length span still shows as a one-day
  chip.

  A task with planned clock times shows them (`planned_events/5`), and a
  task with a deadline gets a marker at its day and time
  (`deadline_event/4`, in the viewer's `offset`) — also a subtask with no
  bar of its own (`bar_item?/1`): the boss set a deadline and looked for it
  on the calendar (2026-10-30).

  Returns `{events, meta}` — `meta` keyed by EVENT id (a deadline marker is
  `"deadline:<uuid>"`) with `:assignment_uuid` / `:project_uuid` /
  `:project_name` / `:status` / `:late` for the day popup's rows, the
  overdue filter, and click navigation. A deadline's `:late` is "missed".

  Options:

    * `:now` — a UTC `NaiveDateTime`; when given, a not-done task whose span
      ended before it is **late**: its chip/bar gets the late marker class
      and its meta entry `late: true`. Without `:now` nothing is flagged
      (pure date math only).
    * `:late_class` — the marker class for late chips/bars (defaults to the
      red inset ring; pass `late_marker_class(read())` to honor
      the configured marker).
    * `:deadline_now` — the UTC `DateTime` deadlines are missed against
      (defaults to `:now`; none: no deadline reads as missed).
  """
  @spec task_events(
          [{map(), PhoenixKitProjects.ScheduleLayout.span()}],
          String.t() | nil,
          String.t(),
          keyword()
        ) ::
          {[Event.t()], %{optional(String.t()) => map()}}
  def task_events(items_with_spans, lang, offset \\ "0", opts \\ []) do
    now = Keyword.get(opts, :now)
    late_class = Keyword.get(opts, :late_class, @late_class)
    deadline_now = Keyword.get(opts, :deadline_now, now && DateTime.from_naive!(now, "Etc/UTC"))

    items_with_spans
    |> Enum.flat_map(fn {item, span} ->
      %{assignment: a, project: project} = item
      {bg, text} = color_for(project.uuid)
      late? = task_late?(a, span, now)
      title = Assignment.label(a, lang) || gettext("(untitled task)")

      entry = %{
        assignment_uuid: a.uuid,
        project_uuid: project.uuid,
        project_name: Project.localized_name(project, lang),
        status: a.status
      }

      bars =
        if bar_item?(item) do
          # a task with its own dates occupies those days wherever the viewer
          # sits; a computed span is an instant, read in the viewer's frame
          days =
            case span do
              %{pinned: {from, to}} ->
                {from, to}

              _ ->
                start_d = to_date(naive_to_utc(span.start), offset)
                {start_d, Date.add(exclusive_end_date(start_d, span.end, offset), -1)}
            end

          a
          |> planned_events(title, days, :month,
            color: bg,
            text_color: text,
            class: if(late?, do: late_class)
          )
          |> Enum.map(&{&1, Map.put(entry, :late, late?)})
        else
          []
        end

      deadline =
        case a do
          %Assignment{deadline: %DateTime{} = at} ->
            local = at |> PhoenixKit.Utils.Date.shift_to_offset(offset) |> DateTime.to_naive()
            missed? = deadline_missed?(a, deadline_now)
            [{deadline_event(a, title, local, missed?), Map.put(entry, :late, missed?)}]

          _ ->
            []
        end

      bars ++ deadline
    end)
    |> Enum.map_reduce(%{}, fn {event, entry}, meta -> {event, Map.put(meta, event.id, entry)} end)
  end

  # ── Deadlines and planned times ─────────────────────────────────────────────

  @doc """
  Whether a flattened item has a bar of its own on a calendar of many
  projects: a top-level row always, a subtask only with a date of its own —
  otherwise the task it sits under already covers its days.
  """
  @spec bar_item?(map()) :: boolean()
  def bar_item?(%{assignment: %Assignment{parent_uuid: nil}}), do: true
  def bar_item?(%{assignment: %Assignment{} = a}), do: ScheduleLayout.dated?(a)
  def bar_item?(_item), do: true

  @doc """
  The `{item, span}` pairs a calendar of many projects draws from
  `ScheduleLayout.trees/1` output: every task (never a sub-project's own
  row) that has a bar (`bar_item?/1`) or a deadline to mark.
  """
  @spec calendar_items([{[map()], map()}]) :: [{map(), ScheduleLayout.span()}]
  def calendar_items(trees) do
    Enum.flat_map(trees, fn {items, layout} ->
      items
      |> Enum.reject(&Assignment.subproject?(&1.assignment))
      |> Enum.filter(&(bar_item?(&1) or match?(%DateTime{}, &1.assignment.deadline)))
      |> Enum.map(&{&1, Map.fetch!(layout, &1.uuid)})
    end)
  end

  @doc """
  A deadline missed: the moment is past and the task is not done.
  (`nil` for `now` misses nothing.)
  """
  @spec deadline_missed?(map(), DateTime.t() | nil) :: boolean()
  def deadline_missed?(%{deadline: %DateTime{} = at, status: status}, %DateTime{} = now),
    do: status != "done" and DateTime.compare(at, now) == :lt

  def deadline_missed?(_a, _now), do: false

  @doc """
  A task's deadline as a marker at its day and time: `local` is the moment
  as the viewer's wall clock. Red once missed (`missed?`), outlined in red
  while still ahead, greyed once the task is done. A short timed event, so
  a month cell shows it as a chip with its time and a day view puts it in
  its hour. Its id is `"deadline:<assignment uuid>"` (`task_uuid/1`).
  """
  @spec deadline_event(Assignment.t(), String.t(), NaiveDateTime.t(), boolean()) :: Event.t()
  def deadline_event(%Assignment{} = a, title, %NaiveDateTime{} = local, missed?) do
    {color, text, class} =
      cond do
        a.status == "done" -> {"bg-base-200", "text-base-content/60", "line-through"}
        missed? -> {"bg-error", "text-error-content", nil}
        true -> {"bg-error/10", "text-error", "ring-1 ring-inset ring-error/60"}
      end

    {start, finish} = within_day(local, 30 * 60)

    PhoenixLiveCalendar.event("deadline:" <> a.uuid, start,
      title: gettext("Deadline: %{title}", title: title),
      end: finish,
      icon: "⚑",
      color: color,
      text_color: text,
      class: class,
      # Above everything else in a crowded month cell.
      priority: :high,
      extra: %{kind: :deadline, status: a.status, late: missed?}
    )
  end

  @doc """
  A task's planned days (`{first, last}`, inclusive) as calendar events,
  with its planned clock times when it has them (`start_time` / `end_time`,
  wall clock on each planned day).

    * no times — one all-day bar, as before;
    * one day with times — a timed event at those hours;
    * several days with times — on a `:month` grid one all-day bar whose
      title carries the times ("09:00–17:00 Fit the worktop"); on a `:week`
      or `:day` grid a timed block on each planned day (ids
      `"<uuid>@<date>"`).

  `opts` are passed to every event (`:color`, `:text_color`, `:class`,
  `:extra`).
  """
  @spec planned_events(Assignment.t(), String.t(), {Date.t(), Date.t()}, atom(), keyword()) ::
          [Event.t()]
  def planned_events(%Assignment{} = a, title, {from, to}, view, opts \\ []) do
    to = if Date.compare(to, from) == :lt, do: from, else: to

    case {timed?(a), Date.compare(from, to), view} do
      {false, _, _} ->
        [
          PhoenixLiveCalendar.event(
            a.uuid,
            from,
            [title: title, end: Date.add(to, 1), all_day: true] ++ opts
          )
        ]

      {true, :eq, _} ->
        [timed_event(a.uuid, a, from, title, opts)]

      {true, _, view} when view in [:week, :day] ->
        if Date.diff(to, from) > 92 do
          [
            PhoenixLiveCalendar.event(
              a.uuid,
              from,
              [title: times_title(a, title), end: Date.add(to, 1), all_day: true] ++ opts
            )
          ]
        else
          for d <- Date.range(from, to), do: timed_event("#{a.uuid}@#{d}", a, d, title, opts)
        end

      {true, _, _} ->
        [
          PhoenixLiveCalendar.event(
            a.uuid,
            from,
            [title: times_title(a, title), end: Date.add(to, 1), all_day: true] ++ opts
          )
        ]
    end
  end

  @doc """
  The assignment uuid behind a calendar event id — the bar's own id, a
  deadline marker's (`"deadline:<uuid>"`) or a planned day's
  (`"<uuid>@<date>"`).
  """
  @spec task_uuid(term()) :: term()
  def task_uuid("deadline:" <> rest), do: task_uuid(rest)

  def task_uuid(id) when is_binary(id) do
    case String.split(id, "@", parts: 2) do
      [uuid, _date] -> uuid
      _ -> id
    end
  end

  def task_uuid(id), do: id

  @doc """
  A clock time as the site writes it (`L10n.format_time/1`, which follows
  the site's time format).
  """
  @spec clock(Time.t()) :: String.t()
  def clock(%Time{} = t), do: L10n.format_time(DateTime.new!(~D[2000-01-01], t))

  @doc """
  The calendar component's hour labels (`:h12` / `:h24`), read off how the
  site writes a time: one that does not write 13:00 as "13…" uses a 12-hour
  clock.
  """
  @spec time_format() :: :h12 | :h24
  def time_format do
    if String.starts_with?(clock(~T[13:00:00]), "13"), do: :h24, else: :h12
  end

  @doc """
